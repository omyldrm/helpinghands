DROP TABLE IF EXISTS events;
DROP TABLE IF EXISTS volunteers;
DROP TABLE IF EXISTS organizations;

CREATE TABLE volunteers
(
    volunteer_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR(15) NOT NULL,
    last_name     VARCHAR(15) NOT NULL,
    email_address VARCHAR(50) NOT NULL,
    birthday      DATE        NOT NULL,
    is_student    BOOLEAN     NOT NULL,
    photo_url     TEXT
);

CREATE TABLE organizations
(
    organization_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(50) NOT NULL,
    founded_date    DATE,
    average_rating  DOUBLE,
    is_verified     BOOLEAN,
    logo_url        TEXT
);

CREATE TABLE events
(
    event_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(50) NOT NULL,
    event_date      DATE,
    category        ENUM ('CLEANUP', 'FUNDRAISER', 'FOOD_DISTRIBUTION', 'EDUCATION', 'ANIMAL_CARE', 'HEALTHCARE', 'CONCERT'),
    location        VARCHAR(50) NOT NULL,
    status          ENUM ('PLANNED', 'ONGOING', 'COMPLETED', 'CANCELLED'),
    banner_url      TEXT,
    max_volunteers  NUMERIC(2),
    organization_id INTEGER     NOT NULL,
    FOREIGN KEY (organization_id) REFERENCES organizations (organization_id)
);